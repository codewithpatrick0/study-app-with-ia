from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from ..models import User
from ..schemas import UserCreate
from ..security import hash_password

class UserAlreadyExistsError(Exception):
    pass

def create_user(db: Session, data: UserCreate) -> User:
    """Hash the password, save the user and return it with its new id."""
    user = User(
        username=data.username,
        full_name=data.full_name,
        email=data.email,
        hashed_password=hash_password(data.password.get_secret_value()),
    )
    db.add(user)
    try:
        db.commit()
    except IntegrityError:
        # The UNIQUE constraints on username/email rejected a duplicate
        db.rollback()
        raise UserAlreadyExistsError("Username or email already registered")

    db.refresh(user)  # Load the id generated by the database
    return user
