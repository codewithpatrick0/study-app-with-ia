import { useRef, useState } from 'react'
import { UploadBorder } from './home'

export function StudyView({ mesh, cycleNumber, onBack }) {
    const cycle = mesh.cycles.find((c) => c.number === cycleNumber);

    return (
        <main className='study-view'>
            <button type='button' className='link-button' onClick={onBack}>
                ← Volver a la malla
            </button>

            <header className='study-header'>
                <p className='study-eyebrow'>{mesh.career} · {mesh.university}</p>
                <h2 className='study-title'>Ciclo {cycleNumber}</h2>

                <ul className='course-chips'>
                    {cycle.courses.map((course) => (
                        <li key={course}>{course}</li>
                    ))}
                </ul>
            </header>

            <HaveSyllabus />
            {/* TODO: render the markdown study material generated by the AI for this cycle
            <section className='study-content'>
                <p className='study-empty'>Aquí aparecerá tu material de estudio.</p>
            </section>*/}
        </main>
    )
}

export function HaveSyllabus() {
    const fileInputRef = useRef(null);
    const [syllabi, setSyllabi] = useState([]);

    function handleFilesChange(event) {
        const files = Array.from(event.target.files); // FileList → real array, so .map works
        if (files.length === 0) return; // User closed the picker without choosing

        setSyllabi(files);
        // TODO: send the syllabi to the backend together with the cycle
    }

    return (
        <section className='have-syllabus'>
            <h3 className='have-syllabus-title'>¿Tienes los sílabos?</h3>
            <p className='have-syllabus-text'>
                Si tienes los sílabos de tus cursos, súbelos para generar un material de estudio más exacto.
            </p>

            <section className='upload-box'>
                <UploadBorder />

                <p className='upload-box-label'>
                    <strong>Inserta tus sílabos</strong>
                </p>

                <input
                    type='file'
                    accept='.pdf'
                    multiple // One syllabus per course
                    ref={fileInputRef}
                    onChange={handleFilesChange}
                    hidden
                />

                <button
                    type='button'
                    className='primary-button'
                    onClick={() => fileInputRef.current.click()}
                >
                    Insertar
                </button>

                {syllabi.length > 0 && (
                    <ul className='upload-file-list'>
                        {syllabi.map((file) => (
                            <li key={file.name} className='upload-file-name'>{file.name}</li>
                        ))}
                    </ul>
                )}
            </section>

            {/* TODO: generate the study material from the mesh only */}
            <button type='button' className='link-button'>
                No tengo sílabos, continuar sin ellos
            </button>
        </section>
    )
}
